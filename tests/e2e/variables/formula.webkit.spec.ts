test('one value field replaces literals, references, formulas and CSS with validation and undo', async ({
  page
}) => {
  const canvas = new CanvasHelper(page)
  await page.goto('/?test')
  await canvas.waitForInit()
  const ids = await seedFormulaScene(page)
  await page
    .getByRole('region', { name: 'Variables' })
    .getByRole('button', { name: 'Open variables' })
    .click()
  const dialog = page.getByTestId('variables-dialog')
  await dialog.locator(`[data-variable-id="${ids.width}"]`).click()
  const inspector = dialog.getByTestId('token-inspector')
  const value = inspector.getByRole('textbox', { name: 'Value', exact: true })
  await expect(value).toHaveCount(1)
  await expect(value).toHaveText('8')
  await value.fill('{base} * 3')
  await expect(inspector.getByText('Result: 12', { exact: true })).toBeVisible()
  expect((await formulaSceneState(page, ids)).width).toBe(8)
  await value.press('Enter')
  await expect.poll(async () => (await formulaSceneState(page, ids)).width).toBe(12)

  await value.fill('1 / 0')
  await value.press('Enter')
  await expect(value).toHaveAttribute('aria-invalid', 'true')
  expect((await formulaSceneState(page, ids)).width).toBe(12)
  await value.press('Escape')
  await expect(value).toContainText('* 3')

  await value.fill('clamp(1rem, 4vw, 2rem)')
  await value.press('Enter')
  await expect(page.getByTestId('token-output')).toContainText('clamp(1rem, 4vw, 2rem)')
  expect((await formulaSceneState(page, ids)).width).toBe(12)
  await value.fill('24')
  await value.press('Enter')
  await expect(value).not.toBeFocused()
  await expect.poll(async () => (await formulaSceneState(page, ids)).width).toBe(24)
  await expect(page.getByTestId('token-output')).not.toContainText('clamp(')
  await canvas.pressKey('Meta+z')
  await expect(value).toHaveText('clamp(1rem, 4vw, 2rem)')
  await expect.poll(async () => (await formulaSceneState(page, ids)).width).toBe(12)

  await value.fill('{base}')
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).numberDefinition).toEqual({ aliasId: ids.base })
  await value.fill('16')
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).numberDefinition).toBe(16)

  await value.fill('{base} * 2')
  await value.press('End')
  await value.press('Shift+ArrowLeft')
  await inspector.getByRole('button', { name: 'Insert variable', exact: true }).click()
  const option = page.getByRole('option', { name: 'base 4', exact: true })
  await expect(option).toContainText('4')
  await option.click()
  await expect(value.locator('[data-reference]')).toHaveCount(2)
  await expect(value).toBeFocused()
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).width).toBe(16)

  await dialog.locator(`[data-variable-id="${ids.visible}"]`).click()
  await expect(inspector.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('visible')
  await expect(value).toHaveText('true')
  await value.fill('NOT {enabled}')
  await expect(inspector.getByText('Result: false', { exact: true })).toBeVisible()
  await value.press('Enter')
  await expect.poll(async () => (await formulaSceneState(page, ids)).visible).toBe(false)
  await value.fill('true')
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).booleanDefinition).toBe(true)
  const preview = test.info().outputPath('unified-token-value.png')
  await inspector.screenshot({ path: preview })
  await test.info().attach('unified-token-value', { path: preview, contentType: 'image/png' })
  canvas.assertNoErrors()
})

test('references are removable atomic pills with editable operators and plain source on copy', async ({
  page
}) => {
  const canvas = new CanvasHelper(page)
  await page.goto('/?test')
  await canvas.waitForInit()
  const ids = await seedFormulaScene(page)
  await page
    .getByRole('region', { name: 'Variables' })
    .getByRole('button', { name: 'Open variables' })
    .click()
  const dialog = page.getByTestId('variables-dialog')
  await dialog.locator(`[data-variable-id="${ids.width}"]`).click()
  const inspector = dialog.getByTestId('token-inspector')
  const value = inspector.getByRole('textbox', { name: 'Value', exact: true })
  await value.fill('{base} * 2')
  const pill = value.locator('[data-reference]')
  await expect(pill).toHaveText('base4')
  await expect(pill).toHaveAttribute('contenteditable', 'false')
  await expect(value).not.toContainText('{')
  await value.press('Meta+a')
  const copied = await value.evaluate((element) => {
    const clipboard = new DataTransfer()
    element.dispatchEvent(
      new ClipboardEvent('copy', { clipboardData: clipboard, bubbles: true, cancelable: true })
    )
    return clipboard.getData('text/plain')
  })
  expect(copied).toBe('{base} * 2')
  await value.getByRole('button', { name: 'Remove base' }).click()
  await expect(pill).toHaveCount(0)
  await value.press('Meta+z')
  await expect(pill).toHaveCount(1)
  await value.getByRole('button', { name: 'Remove base' }).press('Enter')
  await expect(pill).toHaveCount(0)
  await expect(value).toHaveAttribute('aria-invalid', 'true')
  await page.keyboard.insertText('3')
  await expect(inspector.getByText('Result: 6', { exact: true })).toBeVisible()
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).width).toBe(6)

  await value.fill('{base}')
  await value.press('End')
  await value.press('Backspace')
  await expect(pill).toHaveCount(0)
  await expect(value).toHaveText('')
  await value.fill('{base} + 1')
  await value.press('End')
  await page.keyboard.insertText('0')
  await expect(inspector.getByText('Result: 14', { exact: true })).toBeVisible()
  await value.press('Meta+z')
  await expect(inspector.getByText('Result: 5', { exact: true })).toBeVisible()
  await value.press('Meta+Shift+z')
  await expect(inspector.getByText('Result: 14', { exact: true })).toBeVisible()
  await value.press('Home')
  await page.keyboard.type('2 * ')
  await expect(inspector.getByText('Result: 18', { exact: true })).toBeVisible()
  await value.press('Home')
  await value.press('Delete')
  await page.keyboard.type('3')
  await expect(inspector.getByText('Result: 22', { exact: true })).toBeVisible()
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).width).toBe(22)
  await inspector.screenshot({ path: test.info().outputPath('formula-pills.png') })
  canvas.assertNoErrors()
})

test('reference picker and pills show the numeric value of the edited mode', async ({ page }) => {
  const canvas = new CanvasHelper(page)
  await page.goto('/?test')
  await canvas.waitForInit()
  const ids = await seedFormulaScene(page)
  await page.evaluate(({ base, width }) => {
    const editor = window.openPencil?.getStore?.()
    const variable = editor?.graph.variables.get(base)
    if (!editor || !variable) throw new Error('Missing variable')
    const mode = editor.graph.createMode(variable.collectionId, 'Dense')
    if (!mode) throw new Error('Missing mode')
    editor.updateVariableValue(base, mode, 2)
    editor.updateVariableValue(width, mode, 8)
  }, ids)
  await page
    .getByRole('region', { name: 'Variables' })
    .getByRole('button', { name: 'Open variables' })
    .click()
  const dialog = page.getByTestId('variables-dialog')
  await dialog.locator(`[data-variable-id="${ids.width}"]`).click()
  const inspector = dialog.getByTestId('token-inspector')
  const dense = inspector.getByRole('textbox', { name: 'Dense', exact: true })
  await dense.fill('{base} * 2')
  await expect(dense.locator('[data-reference]')).toHaveText('base2')
  await inspector.getByRole('button', { name: 'Insert variable', exact: true }).last().click()
  await expect(page.getByRole('option', { name: 'base 2', exact: true })).toBeVisible()
  canvas.assertNoErrors()
})

test('redo preserves the selection restored after an external value update', async ({ page }) => {
  const canvas = new CanvasHelper(page)
  await page.goto('/?test')
  await canvas.waitForInit()
  const ids = await seedFormulaScene(page)
  await updateFormulaNumber(page, ids, 1234)
  await page
    .getByRole('region', { name: 'Variables' })
    .getByRole('button', { name: 'Open variables' })
    .click()
  const dialog = page.getByTestId('variables-dialog')
  await dialog.locator(`[data-variable-id="${ids.width}"]`).click()
  const value = dialog
    .getByTestId('token-inspector')
    .getByRole('textbox', { name: 'Value', exact: true })
  await value.press('Home')
  await value.press('ArrowRight')
  await value.press('Shift+ArrowRight')
  await updateFormulaNumber(page, ids, 5678)
  await expect(value).toHaveText('5678')
  await expect(value).toBeFocused()
  await value.press('Meta+z')
  await expect(value).toHaveText('1234')
  await value.press('Meta+Shift+z')
  await expect(value).toHaveText('5678')
  await page.keyboard.insertText('9')
  await expect(value).toHaveText('5978')
  await value.press('Enter')
  expect((await formulaSceneState(page, ids)).width).toBe(5978)
  canvas.assertNoErrors()
})
