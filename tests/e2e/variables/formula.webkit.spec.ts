test('a CSS expression completes token names as var() pills and functions', async ({ page }) => {
  const canvas = new CanvasHelper(page)
  await page.goto('/?test')
  await canvas.waitForInit()
  const ids = await seedFormulaScene(page)
  const { dialog, inspector } = await openToken(page, ids.width)
  await inspector.getByRole('button', { name: 'Add CSS expression' }).click()
  const css = inspector.getByRole('textbox', { name: 'CSS expression', exact: true })
  const completion = dialog.locator('.cm-tooltip-autocomplete')
  await expect(css).toBeFocused()
  await page.keyboard.type('cla')
  await expect(completion.getByRole('option', { name: /^clamp/ })).toBeVisible()
  await page.keyboard.press('Enter')
  await page.keyboard.type('1rem, var(')
  await expect(completion.getByRole('option', { name: /^--base/ })).toBeVisible()
  await expect(completion.getByRole('option', { name: /^clamp/ })).toHaveCount(0)
  await page.keyboard.press('Enter')
  await page.keyboard.type(', 2rem)')
  await expect(css.locator('[data-reference]')).toHaveText('--base')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('token-output')).toContainText('clamp(1rem, var(--base), 2rem)')

  const error = inspector.getByRole('alert')
  await css.press('Meta+a')
  await page.keyboard.insertText('var(--missing)')
  await expect(css).toHaveAttribute('aria-invalid', 'false')
  await css.press('Enter')
  await expect(error).toHaveText('No token is named --missing')
  await page.keyboard.insertText(' ')
  await expect(error).toHaveCount(0)
  await css.press('Meta+a')
  await page.keyboard.insertText('4 apples')
  await css.press('Enter')
  await expect(error).toHaveText('Not a valid value for width')
  await css.press('Meta+a')
  await page.keyboard.insertText('calc(2 * ')
  await inspector.getByRole('button', { name: 'Use a variable' }).last().click()
  await page.getByRole('option', { name: 'base 4px', exact: true }).click()
  await expect(css).toBeFocused()
  await page.keyboard.insertText(')')
  await css.press('Enter')
  await expect(page.getByTestId('token-output')).toContainText('calc(2 * var(--base))')
  canvas.assertNoErrors()
})

