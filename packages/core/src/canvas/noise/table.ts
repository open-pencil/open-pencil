/** Levels a noise effect's alpha takes, 0 to 16 sixteenths. */
export const NOISE_LEVELS = 16

/**
 * The shares of pixels at each level or below for `density`, between the two measured rows
 * around it: a uniform value under the first share is level 0, under the second level 1, and so on.
 */
export function noiseLevelShares(density: number): number[] {
  const at = Math.min(Math.max(density, 0), 1) * (LEVEL_SHARES.length - 1)
  const below = Math.floor(at)
  const above = Math.min(below + 1, LEVEL_SHARES.length - 1)
  const t = at - below
  return LEVEL_SHARES[below].map((share, level) => share + (LEVEL_SHARES[above][level] - share) * t)
}

/** The mean level, 0 to 1, of a noise whose shares are `shares`. */
export function noiseMeanLevel(shares: readonly number[]): number {
  return shares.reduce((sum, share) => sum + (1 - share), 0) / NOISE_LEVELS
}
