// Generates the Rust crate's typed `.fig` model (`crate/src/model.rs`) from the Kiwi schema the
// TypeScript reader decodes with: every definition a `NodeChange` reaches, deserialized from a
// file through serde, and the `NodeChange` field set the crate layers records with.
// usage: bun scripts/model.ts [--check]
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import type { Definition, Field } from '@open-pencil/kiwi/schema-runtime'
import { parseSchema } from '@open-pencil/kiwi/schema-runtime'
import { repoPath } from '@open-pencil/test-support/paths'

const SCHEMA = repoPath('packages/kiwi/src/fig/schema/fig.kiwi')
const OUTPUT = join(import.meta.dir, '..', 'crate', 'src', 'model.rs')
const ROOT = 'NodeChange'

const KEYWORDS = new Set(
  'as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen'.split(
    ' '
  )
)

const PRIMITIVES: Record<string, string> = {
  bool: 'bool',
  byte: 'u8',
  int: 'i32',
  uint: 'u32',
  // Arithmetic on Kiwi's 32-bit floats is done in 64 bits, as the TypeScript reader does it.
  float: 'f64',
  string: 'String',
  int64: 'i64',
  uint64: 'u64'
}

/** `styleIdForFill` as `style_id_for_fill`, `symbolID` as `symbol_id`. */
function snake(name: string): string {
  return (
    name
      // `characterStyleIDs` as one word `Ids`, `rotation3DValue` as `rotation3d`.
      .replace(/IDs/g, 'Ids')
      .replace(
        /(\d)([A-Z])(?=[A-Z][a-z]|$)/g,
        (_, digit: string, letter: string) => digit + letter.toLowerCase()
      )
      .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .toLowerCase()
  )
}

/** `PASS_THROUGH` as `PassThrough`. */
function pascal(name: string): string {
  return name
    .toLowerCase()
    .split('_')
    .map((part) => (part ? part[0].toUpperCase() + part.slice(1) : ''))
    .join('')
}

function identifier(name: string): string {
  const field = snake(name)
  return KEYWORDS.has(field) ? `r#${field}` : field
}

function reachable(definitions: readonly Definition[]): Definition[] {
  const byName = new Map(definitions.map((definition) => [definition.name, definition]))
  const seen = new Set<string>()
  const visit = (name: string): void => {
    const definition = byName.get(name)
    if (!definition || seen.has(name)) return
    seen.add(name)
    for (const field of definition.fields) if (field.type) visit(field.type)
  }
  visit(ROOT)
  return definitions.filter((definition) => seen.has(definition.name))
}

function generate(definitions: readonly Definition[]): string {
  const kinds = new Map(definitions.map((definition) => [definition.name, definition.kind]))
  const typeOf = (field: Field, optional: boolean): string => {
    const name = field.type ?? ''
    let inner = PRIMITIVES[name] ?? name
    if (field.isArray) inner = name === 'byte' ? 'serde_bytes::ByteBuf' : `Vec<${inner}>`
    else if (kinds.get(name) === 'MESSAGE') inner = `Box<${inner}>`
    return optional ? `Option<${inner}>` : inner
  }
  const lines: string[] = []
  const append = (more: readonly string[]): void => {
    for (const line of more) lines.push(line)
  }
  append([
    '//! The records of a `.fig` file as Rust types, generated by `packages/fig/scripts/model.ts`',
    '//! from `packages/kiwi/src/fig/schema/fig.kiwi`; do not edit. A message field a record leaves',
    '//! out is `None`; an enum member this schema does not list is `Unlisted`, by the name the',
    "//! file's own schema gives it.",
    '',
    '#![allow(clippy::all, missing_docs)]',
    '',
    'use std::borrow::Cow;',
    '',
    'use serde::{Deserialize, Deserializer, Serialize};',
    '',
    "/// An enum member's name, borrowed from the file where it can be.",
    "struct Name<'a>(Cow<'a, str>);",
    '',
    "impl<'a> Deserialize<'a> for Name<'a> {",
    "    fn deserialize<D: Deserializer<'a>>(deserializer: D) -> Result<Self, D::Error> {",
    '        struct Visit;',
    "        impl<'a> serde::de::Visitor<'a> for Visit {",
    "            type Value = Name<'a>;",
    '            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {',
    '                formatter.write_str("an enum member\'s name")',
    '            }',
    "            fn visit_borrowed_str<E>(self, name: &'a str) -> Result<Self::Value, E> {",
    '                Ok(Name(Cow::Borrowed(name)))',
    '            }',
    '            fn visit_str<E>(self, name: &str) -> Result<Self::Value, E> {',
    '                Ok(Name(Cow::Owned(name.to_owned())))',
    '            }',
    '        }',
    '        deserializer.deserialize_str(Visit)',
    '    }',
    '}',
    ''
  ])
  for (const definition of definitions) {
    const { name, kind, fields } = definition
    if (kind === 'ENUM') {
      lines.push('#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]', `pub enum ${name} {`)
      for (const member of fields)
        lines.push(`    #[serde(rename = "${member.name}")]`, `    ${pascal(member.name)},`)
      append([
        "    /// A member this schema does not list, by the name the file's schema gives it; empty",
        '    /// when that names none either.',
        '    #[serde(untagged)]',
        '    Unlisted(String),',
        '}',
        '',
        `impl<'a> Deserialize<'a> for ${name} {`,
        "    fn deserialize<D: Deserializer<'a>>(deserializer: D) -> Result<Self, D::Error> {",
        '        Ok(match Name::deserialize(deserializer)?.0.as_ref() {'
      ])
      for (const member of fields)
        lines.push(`            "${member.name}" => Self::${pascal(member.name)},`)
      append([
        '            other => Self::Unlisted(other.to_owned()),',
        '        })',
        '    }',
        '}',
        ''
      ])
      continue
    }
    const message = kind === 'MESSAGE'
    lines.push(
      message
        ? '#[derive(Debug, Clone, Default, PartialEq, Deserialize, Serialize)]\n#[serde(default)]'
        : '#[derive(Debug, Clone, PartialEq, Deserialize, Serialize)]',
      `pub struct ${name} {`
    )
    for (const field of fields) {
      const attributes: string[] = []
      if (snake(field.name) !== field.name) attributes.push(`rename = "${field.name}"`)
      if (message) attributes.push('skip_serializing_if = "Option::is_none"')
      if (attributes.length) lines.push(`    #[serde(${attributes.join(', ')})]`)
      lines.push(`    pub ${identifier(field.name)}: ${typeOf(field, message)},`)
    }
    lines.push('}', '')
    if (message)
      append([
        `impl ${name} {`,
        "    /// Sets every field `other` sets to `other`'s value.",
        '    pub fn overlay(&mut self, other: Self) {',
        ...fields.map((field) => {
          const member = identifier(field.name)
          return `        if other.${member}.is_some() { self.${member} = other.${member}; }`
        }),
        '    }',
        '}',
        ''
      ])
  }
  const root = definitions.find((definition) => definition.name === ROOT)
  if (!root) throw new Error(`fig.kiwi has no ${ROOT}`)
  const variants = root.fields.map((field) => ({ variant: pascal(snake(field.name)), field }))
  append([
    `/// A field of a \`${ROOT}\`, by which records are layered.`,
    '#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]',
    'pub enum NodeField {',
    ...variants.map(({ variant }) => `    ${variant},`),
    '}',
    '',
    'impl NodeField {',
    '    /// The field a schema names `name`, as Kiwi spells it.',
    '    pub fn from_name(name: &str) -> Option<NodeField> {',
    '        Some(match name {',
    ...variants.map(
      ({ variant, field }) => `            "${field.name}" => NodeField::${variant},`
    ),
    '            _ => return None,',
    '        })',
    '    }',
    '}',
    '',
    `impl ${ROOT} {`,
    '    /// Every field, in schema order.',
    `    pub const FIELDS: [NodeField; ${variants.length}] = [`,
    ...variants.map(({ variant }) => `        NodeField::${variant},`),
    '    ];',
    '',
    '    /// Whether the record sets a field.',
    '    pub fn has(&self, field: NodeField) -> bool {',
    '        match field {',
    ...variants.map(
      ({ variant, field }) =>
        `            NodeField::${variant} => self.${identifier(field.name)}.is_some(),`
    ),
    '        }',
    '    }',
    '',
    '    /// Leaves a field out.',
    '    pub fn clear(&mut self, field: NodeField) {',
    '        match field {',
    ...variants.map(
      ({ variant, field }) =>
        `            NodeField::${variant} => self.${identifier(field.name)} = None,`
    ),
    '        }',
    '    }',
    '',
    '    /// Moves a field from `other` into this record, where `other` sets it.',
    '    pub fn take(&mut self, other: &mut Self, field: NodeField) {',
    '        match field {',
    ...variants.map(({ variant, field }) => {
      const name = identifier(field.name)
      return `            NodeField::${variant} => if other.${name}.is_some() { self.${name} = other.${name}.take() },`
    }),
    '        }',
    '    }',
    '',
    "    /// Sets a field to `other`'s value, or leaves it out where `other` does.",
    '    pub fn copy_from(&mut self, other: &Self, field: NodeField) {',
    '        match field {',
    ...variants.map(({ variant, field }) => {
      const name = identifier(field.name)
      return `            NodeField::${variant} => self.${name} = other.${name}.clone(),`
    }),
    '        }',
    '    }',
    '',
    '    /// Whether both records have the same value for a field, or both leave it out.',
    '    pub fn same(&self, other: &Self, field: NodeField) -> bool {',
    '        match field {',
    ...variants.map(({ variant, field }) => {
      const name = identifier(field.name)
      return `            NodeField::${variant} => self.${name} == other.${name},`
    }),
    '        }',
    '    }',
    '',
    '    /// Whether the record sets no field.',
    '    pub fn is_empty(&self) -> bool {',
    '        Self::FIELDS.iter().all(|&field| !self.has(field))',
    '    }',
    '',
    '    /// Leaves out every field `keep` rejects.',
    '    pub fn retain(&mut self, keep: impl Fn(NodeField) -> bool) {',
    '        for field in Self::FIELDS {',
    '            if !keep(field) {',
    '                self.clear(field);',
    '            }',
    '        }',
    '    }',
    '}',
    '',
    ''
  ])
  return lines.join('\n')
}

/** The source as `rustfmt` lays it out, as `cargo fmt --check` expects it. */
async function formatted(source: string): Promise<string> {
  const rustfmt = Bun.spawn(['rustfmt', '--edition', '2024', '--emit', 'stdout'], {
    stdin: new Blob([source]),
    stdout: 'pipe',
    stderr: 'inherit'
  })
  const [text, code] = await Promise.all([new Response(rustfmt.stdout).text(), rustfmt.exited])
  if (code !== 0) throw new Error(`rustfmt exited with ${code}`)
  return text
}

const definitions = reachable(parseSchema(await readFile(SCHEMA, 'utf8')).definitions)
const source = await formatted(generate(definitions))
if (process.argv.includes('--check')) {
  // A checkout may turn the model's line endings into CRLF.
  const current = await readFile(OUTPUT, 'utf8').catch(() => '')
  if (current.replaceAll('\r\n', '\n') !== source) {
    process.stderr.write('crate/src/model.rs is older than fig.kiwi; run bun scripts/model.ts\n')
    process.exit(1)
  }
} else {
  await writeFile(OUTPUT, source)
  process.stdout.write(`Wrote ${definitions.length} definitions to crate/src/model.rs\n`)
}
